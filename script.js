// Массив с данными игр (заглушка для первого спринта)
const ITEMS = [
  { id: "g1", title: "Северная экспедиция", hours: 12, score: 8 },
  { id: "g2", title: "Космический рейнджер", hours: 45, score: 9 },
  { id: "g3", title: "Подземелье теней", hours: 7, score: 6 }
];

// Находим пустой список в HTML, куда будем вставлять карточки
const list = document.querySelector("#list");

// Функция отрисовки карточек на страницу
function renderItems(items) {
  // Проверяем, есть ли вообще игры в массиве
  if (items.length === 0) {
    // Если массив пустой, показываем сообщение вместо списка
    list.innerHTML = '<li class="empty">Библиотека пуста. Добавь первую игру.</li>';
    return; // Выходим из функции, дальше код не выполняем
  }

  // Преобразуем каждую игру в HTML-строку и склеиваем их в одну большую строку
  list.innerHTML = items.map(item => {
    // Шаблонная строка создаёт разметку одной карточки
    return `
      <li class="card" data-id="${item.id}">
        <h3>${item.title}</h3>
        <p>Часы: ${item.hours}</p>
        <p>Оценка: ${item.score} из 10</p>
      </li>
    `;
  }).join(""); // join склеивает массив строк в одну строку без разделителей
}

// Запускаем отрисовку с нашими данными
renderItems(ITEMS);
